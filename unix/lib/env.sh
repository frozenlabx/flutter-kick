#!/usr/bin/env bash
# ==============================================================================
# mobile-toolchain-setup: Environment and Shell Configuration Library
# Manages idempotent PATH / environment injection and uninstallation routines
# ==============================================================================

if [[ -n "${_ENV_LIB_LOADED:-}" ]]; then
    # shellcheck disable=SC2317
    return 0 2>/dev/null || exit 0
fi
_ENV_LIB_LOADED=1

SCRIPT_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ -f "${SCRIPT_LIB_DIR}/ui.sh" ]]; then
    # shellcheck source=/dev/null
    source "${SCRIPT_LIB_DIR}/ui.sh"
fi

# ------------------------------------------------------------------------------
# Markers for Idempotent Block Injection
# ------------------------------------------------------------------------------
ENV_MARKER_START="# >>> MOBILE_TOOLCHAIN_SETUP_START >>>"
ENV_MARKER_END="# <<< MOBILE_TOOLCHAIN_SETUP_END <<<"

# ------------------------------------------------------------------------------
# Generate Environment Block Content
# ------------------------------------------------------------------------------
generate_env_block() {
    local shell_type="$1"
    local java_home="$2"
    local android_home="$3"
    local gradle_home="$4"
    local flutter_home="$5"
    local build_tools_ver="$6"

    if [[ "$shell_type" == "fish" ]]; then
        cat << EOF
${ENV_MARKER_START}
# Auto-generated by mobile-toolchain-setup. Do not edit between markers.
set -gx JAVA_HOME "${java_home}"
set -gx ANDROID_HOME "${android_home}"
set -gx ANDROID_SDK_ROOT "\$ANDROID_HOME"
set -gx GRADLE_HOME "${gradle_home}"

if type -q fish_add_path
    fish_add_path -m "\$JAVA_HOME/bin" "\$ANDROID_HOME/cmdline-tools/latest/bin" "\$ANDROID_HOME/platform-tools" "\$ANDROID_HOME/emulator" "\$ANDROID_HOME/build-tools/${build_tools_ver}" "\$GRADLE_HOME/bin" "${flutter_home}/bin"
else
    set -gx PATH "\$JAVA_HOME/bin" "\$ANDROID_HOME/cmdline-tools/latest/bin" "\$ANDROID_HOME/platform-tools" "\$ANDROID_HOME/emulator" "\$ANDROID_HOME/build-tools/${build_tools_ver}" "\$GRADLE_HOME/bin" "${flutter_home}/bin" \$PATH
end
${ENV_MARKER_END}
EOF
    else
        cat << EOF
${ENV_MARKER_START}
# Auto-generated by mobile-toolchain-setup. Do not edit between markers.
export JAVA_HOME="${java_home}"
export ANDROID_HOME="${android_home}"
export ANDROID_SDK_ROOT="\${ANDROID_HOME}"
export GRADLE_HOME="${gradle_home}"

# Mobile Toolchain PATH additions
export PATH="\${JAVA_HOME}/bin:\${ANDROID_HOME}/cmdline-tools/latest/bin:\${ANDROID_HOME}/platform-tools:\${ANDROID_HOME}/emulator:\${ANDROID_HOME}/build-tools/${build_tools_ver}:\${GRADLE_HOME}/bin:${flutter_home}/bin:\${PATH}"
${ENV_MARKER_END}
EOF
    fi
}

# ------------------------------------------------------------------------------
# Idempotent Injection into Shell Configuration File
# ------------------------------------------------------------------------------
inject_env_block() {
    local target_file="$1"
    local block_content="$2"
    local is_dry_run="${3:-false}"

    local parent_dir
    parent_dir="$(dirname "$target_file")"

    if [[ "$is_dry_run" == "true" ]]; then
        log_dry_run "Would inject environment block into: ${target_file}"
        printf "%s--- Preview of Block for %s ---%s\n" "${CLR_DIM}" "$target_file" "${CLR_RESET}"
        printf "%s\n" "$block_content"
        printf "%s-----------------------------------------------%s\n" "${CLR_DIM}" "${CLR_RESET}"
        return 0
    fi

    # Ensure parent directory exists
    if [[ ! -d "$parent_dir" ]]; then
        mkdir -p "$parent_dir"
    fi

    # Create file if missing
    if [[ ! -f "$target_file" ]]; then
        touch "$target_file"
        log_info "Created configuration file: ${target_file}"
    else
        # Create timestamped backup
        local backup_file
        backup_file="${target_file}.bak.$(date '+%Y%m%d%H%M%S')"
        cp "$target_file" "$backup_file"
        log_debug "Backed up ${target_file} to ${backup_file}"
    fi

    local tmp_block
    tmp_block="$(mktemp)"
    printf "%s\n" "$block_content" > "$tmp_block"

    local tmp_out
    tmp_out="$(mktemp)"

    if grep -F -q "$ENV_MARKER_START" "$target_file" 2>/dev/null; then
        # Replace existing marker block
        awk -v bfile="$tmp_block" '
        BEGIN { in_block = 0 }
        /# >>> MOBILE_TOOLCHAIN_SETUP_START >>>/ {
            in_block = 1
            while ((getline line < bfile) > 0) print line
            close(bfile)
            next
        }
        /# <<< MOBILE_TOOLCHAIN_SETUP_END <<</ {
            in_block = 0
            next
        }
        !in_block { print $0 }
        ' "$target_file" > "$tmp_out"
        mv "$tmp_out" "$target_file"
        log_success "Updated existing mobile-toolchain block in ${target_file}"
    else
        # Append to target file
        cp "$target_file" "$tmp_out"
        # Ensure trailing newline before appending
        if [[ -s "$tmp_out" ]] && [[ "$(tail -c 1 "$tmp_out" 2>/dev/null)" != "" ]]; then
            printf "\n" >> "$tmp_out"
        fi
        cat "$tmp_block" >> "$tmp_out"
        printf "\n" >> "$tmp_out"
        mv "$tmp_out" "$target_file"
        log_success "Injected mobile-toolchain environment into ${target_file}"
    fi

    rm -f "$tmp_block" "$tmp_out"
}

# ------------------------------------------------------------------------------
# Strip Environment Marker Block from File
# ------------------------------------------------------------------------------
strip_env_block() {
    local target_file="$1"
    local is_dry_run="${2:-false}"

    if [[ ! -f "$target_file" ]]; then
        return 0
    fi

    if ! grep -F -q "$ENV_MARKER_START" "$target_file" 2>/dev/null; then
        return 0
    fi

    if [[ "$is_dry_run" == "true" ]]; then
        log_dry_run "Would strip mobile-toolchain marker block from: ${target_file}"
        return 0
    fi

    local backup_file
    backup_file="${target_file}.bak.$(date '+%Y%m%d%H%M%S')"
    cp "$target_file" "$backup_file"
    log_debug "Backed up ${target_file} to ${backup_file} before stripping"

    local tmp_out
    tmp_out="$(mktemp)"

    awk '
    BEGIN { in_block = 0 }
    /# >>> MOBILE_TOOLCHAIN_SETUP_START >>>/ {
        in_block = 1
        next
    }
    /# <<< MOBILE_TOOLCHAIN_SETUP_END <<</ {
        in_block = 0
        next
    }
    !in_block { print $0 }
    ' "$target_file" > "$tmp_out"

    mv "$tmp_out" "$target_file"
    log_success "Cleaned marker block from: ${target_file}"
}

# ------------------------------------------------------------------------------
# Complete Uninstall Routine
# ------------------------------------------------------------------------------
uninstall_toolchain() {
    local is_dry_run="${1:-false}"
    local is_auto_confirm="${2:-false}"
    local android_home="${3:-}"
    local flutter_home="${4:-}"
    local gradle_user_home="${5:-}"

    log_step "Starting mobile-toolchain-setup Uninstallation"

    # 1. Clean shell configuration files
    log_info "Scanning shell configuration files for environment marker blocks..."
    local candidate_rcs=(
        "${HOME}/.zshrc"
        "${HOME}/.bashrc"
        "${HOME}/.bash_profile"
        "${HOME}/.profile"
        "${HOME}/.config/fish/config.fish"
    )

    local cleaned_any=false
    for rc in "${candidate_rcs[@]}"; do
        if [[ -f "$rc" ]] && grep -F -q "$ENV_MARKER_START" "$rc" 2>/dev/null; then
            strip_env_block "$rc" "$is_dry_run"
            cleaned_any=true
        fi
    done

    if [[ "$cleaned_any" == "false" ]]; then
        log_info "No shell configuration files contained mobile-toolchain markers."
    fi

    # 2. Clean SDK Directories
    local dirs_to_check=()
    [[ -n "$android_home" ]] && dirs_to_check+=("$android_home")
    [[ -n "$flutter_home" ]] && dirs_to_check+=("$flutter_home")
    [[ -n "$gradle_user_home" ]] && dirs_to_check+=("$gradle_user_home")

    if [[ ${#dirs_to_check[@]} -gt 0 ]]; then
        printf "\n%sChecking SDK Directories for removal:%s\n" "${CLR_BOLD}" "${CLR_RESET}"
        for d in "${dirs_to_check[@]}"; do
            if [[ -d "$d" ]]; then
                printf "  - Found SDK directory: %s\n" "$d"
                if [[ "$is_dry_run" == "true" ]]; then
                    log_dry_run "Would prompt removal or delete directory: $d"
                else
                    local should_remove=false
                    if [[ "$is_auto_confirm" == "true" ]]; then
                        should_remove=true
                    elif [[ -t 0 ]]; then
                        if prompt_confirm "Permanently remove directory '${d}'?" false; then
                            should_remove=true
                        fi
                    else
                        log_warn "Non-interactive shell without auto-confirm: skipping deletion of $d"
                    fi

                    if [[ "$should_remove" == "true" ]]; then
                        log_info "Removing directory: $d"
                        rm -rf "$d"
                        log_success "Deleted: $d"
                    fi
                fi
            else
                log_debug "Directory not present: $d"
            fi
        done
    fi

    if [[ "$is_dry_run" == "true" ]]; then
        log_success "Dry-run uninstall simulation complete. No files or directories were modified."
    else
        log_success "Uninstallation completed successfully."
        log_info "Please run 'source <shell_rc>' or restart your terminal to reload your PATH."
    fi
}
